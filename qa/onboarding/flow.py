async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(args=['--use-angle=swiftshader'])
    await full(b); await skip_path(b); await existing_user(b)
    await b.close()
  print('\nPASS',len(OK),'FAIL',len(BAD),BAD)
asyncio.run(main())
