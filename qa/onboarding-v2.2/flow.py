"""Onboarding v2.1 flow (6 slots, no flip, bio on the front): gate -> /welcome/ -> account -> issue -> fill every slot (front+back) -> finish -> passport shows all."""
import asyncio,json,sys
from playwright.async_api import async_playwright
from h import *
OK=[];BAD=[]
def check(name,cond,info=''):
  (OK if cond else BAD).append(name); print(('PASS ' if cond else 'FAIL ')+name+(' | '+str(info) if (info!='' and not cond) else ''))
async def ls(pg,k): return await pg.evaluate("k=>localStorage.getItem(k)",k)
async def chip(pg): return (await pg.inner_text('#ob-chip')).replace('\n','').replace(' ','')
async def axe(pg,label):
  await pg.add_script_tag(path=AXE)
  r=await pg.evaluate("async()=>{const r=await axe.run(document,{runOnly:['wcag2a','wcag2aa','best-practice']});return r.violations.map(v=>v.id+':'+v.nodes.length+':'+v.nodes[0].target.join(' ').slice(0,60))}")
  check('axe 0 '+label,not r,r)
async def run(b,w,h):
  print(f'--- viewport {w}x{h}')
  ctx=await b.new_context(viewport={'width':w,'height':h},has_touch=w<800,is_mobile=w<800); pg=await ctx.new_page(); pg.errs=[]; pg.posts=[]
  pg.on('console',lambda m: pg.errs.append(m.text) if m.type=='error' else None); pg.on('pageerror',lambda e: pg.errs.append(str(e)))
  pg.on('request',lambda r: pg.posts.append((r.url,r.post_data)) if r.method!='GET' else None)
  await pg.goto(BASE+'/spot/?id=tochigi-underground-quarry&gate=out',wait_until='load'); await pg.wait_for_selector('.gt-sheet #gt-email',timeout=20000)
  await pg.evaluate("localStorage.removeItem('deepspot-onboarded-v1');localStorage.removeItem('deepspot-onboarding-v1')")
  await pg.fill('#gt-email','flow@example.com'); await js_click(pg,'.gt-go')
  await pg.wait_for_url('**/welcome/**',timeout=15000); await pg.wait_for_selector('#ob-form',timeout=15000); await pg.wait_for_timeout(600)
  check('gate continue lands on /welcome/','/welcome/' in pg.url,pg.url)
  check('from= carries the spot','from=%2Fspot%2F' in pg.url or 'from=/spot/' in pg.url,pg.url)
  check('email prefilled',await pg.input_value('#ob-email')=='flow@example.com')
  ns=await noscroll(pg); check('A no scroll',ns['sh']<=ns['ih'] and ns['sw']<=ns['iw'],ns)
  await axe(pg,'A')
  await js_click(pg,'#ob-form .ob-go'); await pg.wait_for_timeout(250)
  check('empty password blocked',await pg.is_visible('#ob-form'))
  check('pw aria-invalid',await pg.evaluate("document.querySelector('#ob-pw').getAttribute('aria-invalid')")=='true')
  await pg.fill('#ob-pw','short'); await js_click(pg,'#ob-form .ob-go'); await pg.wait_for_timeout(200); check('short pw blocked',await pg.is_visible('#ob-form'))
  await pg.fill('#ob-pw',PW); await pg.wait_for_timeout(100)
  check('meter reacts',await pg.evaluate("+document.querySelector('.ob-meter').dataset.score")>=3)
  await js_click(pg,'#ob-form .ob-go'); await pg.wait_for_timeout(250)
  check('terms required',await pg.is_visible('#ob-form') and 'agree' in await pg.inner_text('#ob-terms-h'))
  await js_click(pg,'.ob-show'); check('show password',await pg.evaluate("document.querySelector('#ob-pw').type")=='text'); await js_click(pg,'.ob-show')
  await js_click(pg,'#ob-terms')
  ns=await noscroll(pg); check('A errors no scroll',ns['sh']<=ns['ih'],ns)
  await js_click(pg,'#ob-form .ob-go')
  await pg.wait_for_selector('.ob-stage',state='visible',timeout=5000)
  check('issuing class on',await pg.evaluate("document.querySelector('.ob-b').classList.contains('is-issuing')"))
  await pg.wait_for_function("()=>!document.querySelector('.ob-b').classList.contains('is-issuing')",timeout=8000)
  sess=json.loads(await ls(pg,'deepspot-session-preview')); check('session free + email',sess=={'state':'free','email':'flow@example.com'},sess)
  dump=await pg.evaluate("JSON.stringify([Object.entries(localStorage),Object.entries(sessionStorage)])")
  check('password never stored',PW not in dump); check('password never sent',not any(PW in (d or '') or PW in u for u,d in pg.posts))
  ns=await noscroll(pg); check('B no scroll',ns['sh']<=ns['ih'] and ns['sw']<=ns['iw'],ns)
  check('chip 0/6',await chip(pg)=='0/6',await chip(pg))
  check('no flip button / back face',await pg.evaluate("!document.querySelector('#ob-flip,.ob-back,.ob-flipb')"))
  n=await pg.evaluate("document.querySelectorAll('.ob-b .ob-slot').length"); check('slots present (photo,name,type,bio,mark,style)',n==6,n)
  names=await pg.evaluate("[...document.querySelectorAll('.ob-b .ob-slot')].map(b=>b.getAttribute('aria-label'))"); check('slot labels',all(names),names)
  check('name slot says required','required' in names[1],names[1])
  await axe(pg,'B')
  await js_click(pg,'#ob-fin'); await pg.wait_for_timeout(200)
  check('finish disabled until required',await pg.evaluate("document.querySelector('#ob-fin').getAttribute('aria-disabled')")=='true')
  check('nudge on first empty required',await pg.evaluate("document.querySelector('[data-slot=photo].is-nudge')!==null"))
  await slot(pg,'name'); await axe(pg,'sheet name')
  check('sheet is dialog',await pg.evaluate("document.querySelector('.ob-sheet').getAttribute('role')")=='dialog')
  check('focus inside sheet',await pg.evaluate("document.querySelector('.ob-sheet').contains(document.activeElement)"))
  for _ in range(8): await pg.keyboard.press('Tab')
  check('focus trapped',await pg.evaluate("document.querySelector('.ob-sheet').contains(document.activeElement)"))
  await pg.keyboard.press('Escape'); await pg.wait_for_selector('.ob-layer',state='hidden',timeout=3000); await pg.wait_for_timeout(200)
  check('Escape closes + focus returns to slot',await pg.evaluate("document.activeElement.dataset.slot")=='name',await pg.evaluate("document.activeElement.outerHTML.slice(0,80)"))
  await slot(pg,'name')
  for val,expect in [('lampbane','taken'),('admin','reserved'),('ab','at least'),('a b','letters'),('.dot','start and end')]:
    await pg.fill('#ob-user',val); await pg.wait_for_timeout(120); t=await pg.inner_text('#ob-user-h'); check(f'username {val!r} -> {expect}',expect in t,t)
  await pg.fill('#ob-name','Flow Tester'); chips=await pg.evaluate("[...document.querySelectorAll('#ob-sug .ob-chip')].map(b=>b.textContent)"); check('suggestions',len(chips)>=3,chips)
  await pg.fill('#ob-user','lampbane'); await js_click(pg,'.ob-sh-done'); await pg.wait_for_timeout(300)
  check('taken handle blocks done',await pg.is_visible('.ob-sheet'))
  await pg.fill('#ob-user','flow.tester'); await pg.wait_for_timeout(150); check('free handle ok','free' in await pg.inner_text('#ob-user-h'))
  await close_sheet(pg)
  check('chip 1/6 after name',await chip(pg)=='1/6',await chip(pg))
  check('card name',await pg.evaluate("document.querySelectorAll('.ob-front .pp-rows dd')[0].textContent")=='Flow Tester')
  check('card user',await pg.evaluate("document.querySelectorAll('.ob-front .pp-rows dd')[1].textContent")=='@flow.tester')
  await pg.reload(wait_until='load'); await pg.wait_for_selector('.ob-stage',state='visible'); await pg.wait_for_timeout(600)
  check('refresh lands on B',await pg.is_visible('.ob-stage') and not await pg.is_visible('#ob-form'))
  check('refresh keeps name',await pg.evaluate("document.querySelectorAll('.ob-front .pp-rows dd')[0].textContent")=='Flow Tester')
  await do_arch(pg,'urbex-rat'); check('arch on card',await pg.evaluate("document.querySelector('[data-r=type] dd').textContent")=='urbex rat')
  await slot(pg,'arch'); await axe(pg,'sheet arch'); await close_sheet(pg,'x')
  await do_mole(pg); check('mole saved',bool(json.loads(await ls(pg,'deepspot-profile-draft-v1')).get('mole',{}).get('png')))
  check('chip 3/6',await chip(pg)=='3/6',await chip(pg))
  check('finish ready after required',await pg.evaluate("document.querySelector('#ob-fin').getAttribute('aria-disabled')")=='false')
  await do_mark(pg); check('mark saved',bool(json.loads(await ls(pg,'deepspot-profile-draft-v1')).get('signatureArt')))
  await slot(pg,'mark'); await axe(pg,'sheet mark'); await close_sheet(pg,'x')
  await do_style(pg,'holo','aurora'); st=json.loads(await ls(pg,'deepspot-passport-style-v1')); check('style saved',st=={'bg':'aurora','foil':'holo'},st)
  check('foil on card',await pg.evaluate("document.querySelector('.ed-pobj').dataset.foil")=='holo')
  await slot(pg,'style'); await axe(pg,'sheet style'); await close_sheet(pg,'x')
  await do_bio(pg); check('bio saved',(json.loads(await ls(pg,'deepspot-profile-draft-v1')).get('bio') or '').startswith('I go looking'))
  check('bio on the card front',await pg.evaluate("document.querySelector('.ob-front [data-bio]').textContent.startsWith('I go looking')"))
  check('bio fits (no overflow)',await pg.evaluate("(()=>{const t=document.querySelector('.ob-front [data-bio]');return t.scrollHeight<=t.parentElement.clientHeight+1})()"))
  await pg.evaluate("localStorage.setItem('deepspot-want-to-go-v1','[]')")
  await slot(pg,'bio'); await axe(pg,'sheet bio'); await close_sheet(pg,'x')
  check('chip 6/6',await chip(pg)=='6/6',await chip(pg))
  ns=await noscroll(pg); check('B filled no scroll',ns['sh']<=ns['ih'] and ns['sw']<=ns['iw'],ns)
  await axe(pg,'B filled')
  await js_click(pg,'#ob-fin'); await pg.wait_for_selector('.ob-stage.is-final',timeout=4000); await pg.wait_for_timeout(500)
  check('big ISSUED stamp shown',await pg.evaluate("getComputedStyle(document.querySelector('.ob-issued')).opacity")!='0')
  await pg.wait_for_url('**/profile/**welcome=1**',timeout=8000); await pg.wait_for_timeout(2500)
  check('onboarded flag set',bool(await ls(pg,'deepspot-onboarded-v1')))
  txt=await pg.inner_text('body')
  check('passport shows name',('Flow Tester' in txt)); check('passport shows bio','abandoned quarries' in txt)
  check('passport shows handle','flow.tester' in txt)
  await pg.goto(BASE+'/welcome/',wait_until='load'); await pg.wait_for_timeout(1500); check('welcome redirects when finished','/profile/' in pg.url,pg.url)
  real=[e for e in pg.errs if 'favicon' not in e and 'googleapis' not in e and 'ERR_' not in e]; check('console 0 errors',not real,real[:3])
  await ctx.close()
async def skip_and_keys(b):
  print('--- keyboard + skip issue')
  ctx=await b.new_context(viewport={'width':1440,'height':900}); pg=await ctx.new_page()
  await pg.goto(BASE+'/welcome/?reset=1',wait_until='load'); await pg.evaluate("localStorage.setItem('deepspot-session-preview',JSON.stringify({state:'free',email:'k@example.com'}))")
  await pg.goto(BASE+'/welcome/',wait_until='load'); await pg.wait_for_selector('#ob-form'); await pg.fill('#ob-pw',PW); await js_click(pg,'#ob-terms')
  await pg.focus('#ob-pw'); await pg.keyboard.press('Enter')
  await pg.wait_for_selector('.ob-stage',state='visible',timeout=5000); await pg.wait_for_timeout(300)
  await pg.mouse.click(300,300)
  await pg.wait_for_function("()=>!document.querySelector('.ob-b').classList.contains('is-issuing')",timeout=1500); check('tap skips the issue animation',True)
  await pg.focus('[data-slot=name]'); await pg.keyboard.press('Enter'); await pg.wait_for_selector('.ob-sheet.is-open',timeout=3000); check('Enter opens a slot',True)
  check('popover on desktop',await pg.evaluate("document.querySelector('.ob-sheet').classList.contains('is-pop')"))
  await pg.keyboard.press('Escape'); await ctx.close()
  ctx=await b.new_context(viewport={'width':390,'height':844},reduced_motion='reduce'); pg=await ctx.new_page()
  await pg.goto(BASE+'/welcome/?reset=1',wait_until='load'); await pg.evaluate("localStorage.setItem('deepspot-session-preview',JSON.stringify({state:'free',email:'k@example.com'}))")
  await pg.goto(BASE+'/welcome/',wait_until='load'); await pg.wait_for_selector('#ob-form'); await pg.fill('#ob-pw',PW); await js_click(pg,'#ob-terms'); await js_click(pg,'#ob-form .ob-go')
  await pg.wait_for_selector('.ob-stage',state='visible',timeout=2000); check('reduced motion: B within 2s',True)
  await ctx.close()
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(args=["--use-angle=swiftshader"])
    for w,h in [(390,844),(1440,900)] if len(sys.argv)<2 else [(int(sys.argv[1]),int(sys.argv[2]))]:
      try: await run(b,w,h)
      except Exception as e: BAD.append(f'CRASH {w}: {e!s:.300}'); print('CRASH',e)
    try: await skip_and_keys(b)
    except Exception as e: BAD.append(f'CRASH keys: {e!s:.300}'); print('CRASH',e)
    await b.close()
  print(f'\n{len(OK)} pass, {len(BAD)} fail'); [print(' FAIL',x) for x in BAD]
asyncio.run(main())
